
from phishguard.config import DATABASE_BACKEND


SQLITE_SCHEMA = """
CREATE TABLE IF NOT EXISTS campaigns (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL CHECK(length(name) BETWEEN 1 AND 100),
    tracking_code TEXT NOT NULL UNIQUE,
    status TEXT NOT NULL DEFAULT 'draft'
        CHECK(status IN ('draft', 'active', 'paused', 'completed')),
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS participants (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    campaign_id INTEGER NOT NULL,
    participant_token TEXT NOT NULL
        CHECK(length(participant_token) BETWEEN 20 AND 100),
    participant_name TEXT NOT NULL
        CHECK(length(participant_name) BETWEEN 1 AND 100),
    submitted_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    consent_ip INTEGER NOT NULL DEFAULT 0 CHECK(consent_ip IN (0,1)),
    ip_address TEXT CHECK(ip_address IS NULL OR length(ip_address)<=45),
    consent_device INTEGER NOT NULL DEFAULT 0
        CHECK(consent_device IN (0,1)),
    user_agent TEXT CHECK(user_agent IS NULL OR length(user_agent)<=500),
    browser_name TEXT,
    browser_version TEXT,
    os_name TEXT,
    device_type TEXT,
    consent_activity INTEGER NOT NULL DEFAULT 0
        CHECK(consent_activity IN (0,1)),
    FOREIGN KEY(campaign_id) REFERENCES campaigns(id) ON DELETE CASCADE,
    UNIQUE(campaign_id, participant_token),
    CHECK(consent_ip=1 OR ip_address IS NULL),
    CHECK(
        consent_device=1 OR
        (user_agent IS NULL AND browser_name IS NULL
         AND browser_version IS NULL AND os_name IS NULL
         AND device_type IS NULL)
    )
);

CREATE TABLE IF NOT EXISTS events (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    campaign_id INTEGER NOT NULL,
    event_type TEXT NOT NULL CHECK(event_type IN (
        'page_visit', 'training_page_view',
        'form_interaction', 'simulation_complete'
    )),
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_agent TEXT,
    participant_id INTEGER,
    FOREIGN KEY(campaign_id) REFERENCES campaigns(id) ON DELETE CASCADE,
    FOREIGN KEY(participant_id) REFERENCES participants(id)
        ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_participants_campaign
ON participants(campaign_id);

CREATE INDEX IF NOT EXISTS idx_events_campaign_created
ON events(campaign_id, created_at);

CREATE INDEX IF NOT EXISTS idx_events_participant
ON events(participant_id);
"""


POSTGRES_SCHEMA = """
CREATE TABLE IF NOT EXISTS campaigns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    tracking_code VARCHAR(100) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'draft'
        CHECK(status IN ('draft', 'active', 'paused', 'completed')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS participants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id BIGINT NOT NULL REFERENCES campaigns(id)
        ON DELETE CASCADE,
    participant_token VARCHAR(100) NOT NULL,
    participant_name VARCHAR(100) NOT NULL,
    submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    consent_ip BOOLEAN NOT NULL DEFAULT FALSE,
    ip_address VARCHAR(45),
    consent_device BOOLEAN NOT NULL DEFAULT FALSE,
    user_agent VARCHAR(500),
    browser_name VARCHAR(100),
    browser_version VARCHAR(50),
    os_name VARCHAR(100),
    device_type VARCHAR(20),
    consent_activity BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE(campaign_id, participant_token),
    CHECK(consent_ip OR ip_address IS NULL),
    CHECK(
        consent_device OR
        (user_agent IS NULL AND browser_name IS NULL
         AND browser_version IS NULL AND os_name IS NULL
         AND device_type IS NULL)
    ),
    CHECK(device_type IS NULL OR device_type IN (
        'desktop', 'mobile', 'tablet', 'unknown'
    ))
);

CREATE TABLE IF NOT EXISTS events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id BIGINT NOT NULL REFERENCES campaigns(id)
        ON DELETE CASCADE,
    event_type VARCHAR(40) NOT NULL CHECK(event_type IN (
        'page_visit', 'training_page_view',
        'form_interaction', 'simulation_complete'
    )),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_agent VARCHAR(500),
    participant_id BIGINT REFERENCES participants(id)
        ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_participants_campaign
ON participants(campaign_id);

CREATE INDEX IF NOT EXISTS idx_events_campaign_created
ON events(campaign_id, created_at);

CREATE INDEX IF NOT EXISTS idx_events_participant
ON events(participant_id);

CREATE TABLE IF NOT EXISTS schema_version (
    version INTEGER PRIMARY KEY,
    applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
"""


def initialize_schema(connection):
    if DATABASE_BACKEND == "sqlite":
        connection.executescript(SQLITE_SCHEMA)
        return

    if DATABASE_BACKEND == "postgresql":
        statements = [
            statement.strip()
            for statement in POSTGRES_SCHEMA.split(";")
            if statement.strip()
        ]

        for statement in statements:
            connection.execute(statement)

        connection.execute(
            """
            INSERT INTO schema_version (version)
            VALUES (%s)
            ON CONFLICT (version) DO NOTHING
            """,
            (1,),
        )

        return

    raise RuntimeError("Unsupported database backend.")
